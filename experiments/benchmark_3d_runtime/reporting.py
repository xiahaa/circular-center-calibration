"""Aggregate and write the paper Table III runtime artifacts."""

from __future__ import annotations

import csv
from collections import defaultdict
from pathlib import Path
from typing import Any, Dict, Mapping, Sequence

import numpy as np


def summarize_workers(workers: Sequence[Mapping[str, Any]]) -> Sequence[Mapping[str, Any]]:
    grouped: Dict[str, list] = defaultdict(list)
    for worker in workers:
        grouped[str(worker["method"])].append(worker)
    rows = []
    for method, values in grouped.items():
        latencies = np.asarray(
            [latency for value in values for latency in value["latencies_ms"]],
            dtype=float,
        )
        rss = np.asarray([value["peak_rss_mib"] for value in values], dtype=float)
        rows.append(
            {
                "method": method,
                "timed_repetitions": int(len(latencies)),
                "process_repetitions": len(values),
                "p50_ms": float(np.percentile(latencies, 50.0)),
                "p95_ms": float(np.percentile(latencies, 95.0)),
                "median_peak_rss_mib": float(np.median(rss)),
            }
        )
    return rows


def order_rows(
    rows: Sequence[Mapping[str, Any]], method_order: Sequence[str]
) -> Sequence[Mapping[str, Any]]:
    by_method = {str(row["method"]): row for row in rows}
    return [by_method[name] for name in method_order if name in by_method]


def write_raw_csv(path: Path, workers: Sequence[Mapping[str, Any]]) -> None:
    fields = ("method", "process_index", "repetition", "latency_ms")
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        for worker in workers:
            for repetition, latency in enumerate(worker["latencies_ms"]):
                writer.writerow(
                    {
                        "method": worker["method"],
                        "process_index": worker["process_index"],
                        "repetition": repetition,
                        "latency_ms": latency,
                    }
                )


def write_process_csv(path: Path, workers: Sequence[Mapping[str, Any]]) -> None:
    fields = (
        "method",
        "process_index",
        "timed_repetitions",
        "warmup_repetitions",
        "peak_rss_mib",
    )
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        writer.writerows(
            {field: worker.get(field) for field in fields} for worker in workers
        )


def write_summary_csv(path: Path, rows: Sequence[Mapping[str, Any]]) -> None:
    fields = (
        "method",
        "timed_repetitions",
        "process_repetitions",
        "p50_ms",
        "p95_ms",
        "median_peak_rss_mib",
    )
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def write_tex_table(path: Path, rows: Sequence[Mapping[str, Any]], point_count: int) -> None:
    lines = [
        "% Generated by experiments/benchmark_3d_runtime.",
        "\\begin{tabular}{lrrr}",
        "\\toprule",
        "Method ($n={}$) & p50 (ms) & p95 (ms) & Peak RSS (MiB) \\\\".format(
            point_count
        ),
        "\\midrule",
    ]
    for row in rows:
        lines.append(
            "{} & {:.3f} & {:.3f} & {:.1f} \\\\".format(
                row["method"],
                row["p50_ms"],
                row["p95_ms"],
                row["median_peak_rss_mib"],
            )
        )
    lines.extend(("\\bottomrule", "\\end{tabular}", ""))
    path.write_text("\n".join(lines), encoding="utf-8")


def compare_with_reference(
    rows: Sequence[Mapping[str, Any]], reference: Mapping[str, Any]
) -> Sequence[Mapping[str, Any]]:
    comparisons = []
    for row in rows:
        expected = reference["methods"][str(row["method"])]
        comparisons.append(
            {
                "method": row["method"],
                "observed_p50_ms": row["p50_ms"],
                "paper_p50_ms": float(expected["p50_ms"]),
                "observed_p95_ms": row["p95_ms"],
                "paper_p95_ms": float(expected["p95_ms"]),
                "observed_peak_rss_mib": row["median_peak_rss_mib"],
                "paper_peak_rss_mib": float(expected["peak_rss_mib"]),
            }
        )
    return comparisons


def write_comparison_csv(path: Path, rows: Sequence[Mapping[str, Any]]) -> None:
    fields = (
        "method",
        "observed_p50_ms",
        "paper_p50_ms",
        "observed_p95_ms",
        "paper_p95_ms",
        "observed_peak_rss_mib",
        "paper_peak_rss_mib",
    )
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


